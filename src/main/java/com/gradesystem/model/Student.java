package com.gradesystem.model;

import com.gradesystem.util.AppConstants;

/**
 * ABSTRACT parent of {@link RegularStudent} and {@link HonorsStudent}.
 *
 * <p>Change from Lab 1: a Student no longer talks to the GradeManager.
 * It only holds the student's own data (Single Responsibility).
 * Averages are calculated by the services and passed in when needed.</p>
 *
 * <p>Open/Closed: to add a new student type (for example "ExchangeStudent")
 * you write a new subclass. No existing class has to change.</p>
 */
public abstract class Student implements Searchable, Exportable {

    private final String studentId;
    private String name;
    private int age;
    private String email;
    private String phone;
    private String status;

    /**
     * Creates a student. The ID is generated by the StudentManager.
     *
     * @param studentId unique ID such as STU001
     * @param name      full name
     * @param age       age in years
     * @param email     email address
     * @param phone     phone number
     */
    protected Student(String studentId, String name, int age, String email, String phone) {
        this.studentId = studentId;
        this.name = name;
        this.age = age;
        this.email = email;
        this.phone = phone;
        this.status = AppConstants.STATUS_ACTIVE;
    }

    /**
     * Every subclass says what type of student it is.
     *
     * @return for example "Regular" or "Honors"
     */
    public abstract String getStudentType();

    /**
     * Every subclass decides its own passing grade.
     *
     * @return the passing grade in percent
     */
    public abstract double getPassingGrade();

    /**
     * Checks whether an average is high enough to pass.
     *
     * @param average the student's average grade
     * @return true when the average reaches the passing grade
     */
    public boolean isPassing(double average) {
        return average >= getPassingGrade();
    }

    /**
     * Only honors students can be honors eligible, so by default this is false.
     * {@link HonorsStudent} overrides it. This replaces the old {@code instanceof}
     * check and keeps every subclass usable as a Student (Liskov Substitution).
     *
     * @param average the student's average grade
     * @return false for normal students
     */
    public boolean isHonorsEligible(double average) {
        return false;
    }

    /**
     * Partial, case-insensitive match on the student's name.
     *
     * @param keyword part of a name
     * @return true if the name contains the keyword
     */
    @Override
    public boolean matchesKeyword(String keyword) {
        return name.toLowerCase().contains(keyword.trim().toLowerCase());
    }

    /**
     * {@return "STU001 | Alice Johnson | Regular | alice@school.edu"}
     */
    @Override
    public String toExportLine() {
        return studentId + " | " + name + " | " + getStudentType() + " | " + email;
    }

    /** {@return the unique student ID} */
    public String getStudentId() { return studentId; }

    /** {@return the full name} */
    public String getName() { return name; }

    /**
     * Changes the name.
     *
     * @param name the new name
     */
    public void setName(String name) { this.name = name; }

    /** {@return the age} */
    public int getAge() { return age; }

    /**
     * Changes the age.
     *
     * @param age the new age
     */
    public void setAge(int age) { this.age = age; }

    /** {@return the email} */
    public String getEmail() { return email; }

    /**
     * Changes the email.
     *
     * @param email the new email
     */
    public void setEmail(String email) { this.email = email; }

    /** {@return the phone number} */
    public String getPhone() { return phone; }

    /**
     * Changes the phone.
     *
     * @param phone the new phone number
     */
    public void setPhone(String phone) { this.phone = phone; }

    /** {@return the status, for example "Active"} */
    public String getStatus() { return status; }

    /**
     * Changes the status.
     *
     * @param status the new status
     */
    public void setStatus(String status) { this.status = status; }
}
